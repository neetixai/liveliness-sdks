/**
 * Guided selfie / document capture view for the Neetix Liveliness API.
 *
 * A plain Android [View] (usable from Compose via `AndroidView { ... }`) that
 * shows a CameraX preview with an oval (selfie) or card-shaped (document)
 * guide overlay, gives brightness + hold-still hints from a luma analysis of
 * the live frames, auto-captures after the scene has been stable for
 * [stableMillis] (default 1.5 s) plus a visible countdown, and returns a
 * JPEG resized to <= [maxDimension] px (default 1280) at quality
 * [jpegQuality] (default 80) — matching what the API expects.
 *
 * Usage (the host must hold `android.permission.CAMERA` before [start]):
 * ```kotlin
 * val view = NeetixCaptureView(context).apply {
 *     mode = NeetixCaptureView.Mode.SELFIE
 *     listener = object : NeetixCaptureView.Listener {
 *         override fun onCaptured(jpeg: ByteArray) {
 *             // pass `jpeg` + captureNonce to NeetixClient
 *         }
 *     }
 * }
 * container.addView(view)
 * view.start(lifecycleOwner)
 * // manual fallback: view.capture()
 * ```
 *
 * Each [start] / [rearm] generates a fresh [captureNonce]; send it as the
 * request's `capture_nonce` and (optionally) bind it into a Play Integrity
 * token via [NeetixAttestation].
 */
class NeetixCaptureView @JvmOverloads constructor(
    context: Context,
    attrs: AttributeSet? = null,
    defStyleAttr: Int = 0,
) : FrameLayout(context, attrs, defStyleAttr) {

    /** SELFIE = front camera + oval guide; DOCUMENT = back camera + ID-1 card guide. */
    enum class Mode { SELFIE, DOCUMENT }

    /** Live guidance derived from the analysis stream. */
    enum class Hint { SEARCHING, TOO_DARK, TOO_BRIGHT, HOLD_STILL, STABLE }

    /** All callbacks arrive on the main thread. */
    interface Listener {
        /** Guidance changed — surface it as user-facing copy. */
        fun onHint(hint: Hint) {}

        /** Auto-capture countdown tick; [secondsLeft] counts [countdownSeconds]..1. */
        fun onCountdownTick(secondsLeft: Int) {}

        /** Countdown aborted because the scene became unstable / badly lit. */
        fun onCountdownCancelled() {}

        /** Final JPEG (<= [maxDimension] px, quality [jpegQuality]), rotation applied. */
        fun onCaptured(jpeg: ByteArray) {}

        fun onError(error: Throwable) {}
    }

    // ---------- Tunables (set before start(); sensible defaults) ----------

    /** Capture mode; changing it after [start] rebinds the camera. */
    var mode: Mode = Mode.SELFIE
        set(value) {
            field = value
            overlay.invalidate()
            if (boundOwner != null) bindCamera()
        }

    var listener: Listener? = null

    /** Auto-capture after stability; `false` = manual [capture] only. */
    var autoCapture: Boolean = true

    /** Continuous stable+well-lit time required before the countdown starts. */
    var stableMillis: Long = 1_500L

    /** Countdown length after stability (0 = capture immediately). */
    var countdownSeconds: Int = 3

    /** Mean-luma window (0–255) considered acceptably lit. */
    var minLuma: Float = 60f
    var maxLuma: Float = 205f

    /** Mean per-cell luma delta between frames below which a frame is "still". */
    var motionThreshold: Float = 6f

    /** Output JPEG max dimension / quality. */
    var maxDimension: Int = 1_280
    var jpegQuality: Int = 80

    /**
     * Fresh random hex nonce, regenerated by [start] and [rearm]. Send it as
     * the API request's `capture_nonce` field and use it as the challenge for
     * [NeetixAttestation.requestToken].
     */
    var captureNonce: String = newNonce()
        private set

    // ---------- Internals ----------

    private val previewView = PreviewView(context).apply {
        layoutParams = LayoutParams(LayoutParams.MATCH_PARENT, LayoutParams.MATCH_PARENT)
        scaleType = PreviewView.ScaleType.FILL_CENTER
    }
    private val overlay = OverlayView(context).apply {
        layoutParams = LayoutParams(LayoutParams.MATCH_PARENT, LayoutParams.MATCH_PARENT)
    }

    private val mainHandler = Handler(Looper.getMainLooper())
    private var workExecutor: ExecutorService? = null
    private var cameraProvider: ProcessCameraProvider? = null
    private var boundOwner: LifecycleOwner? = null
    private var imageCapture: ImageCapture? = null

    private var currentHint: Hint = Hint.SEARCHING
    private var stableSince = 0L
    private var countdownLeft = -1 // -1 = not counting
    private var captured = false
    private var capturing = false

    init {
        addView(previewView)
        addView(overlay)
    }

    /**
     * Open the camera and begin analysis. Regenerates [captureNonce]. The
     * caller must already hold the CAMERA runtime permission.
     */
    fun start(lifecycleOwner: LifecycleOwner) {
        boundOwner = lifecycleOwner
        rearm()
        if (workExecutor == null) workExecutor = Executors.newSingleThreadExecutor()
        val future = ProcessCameraProvider.getInstance(context)
        future.addListener({
            try {
                cameraProvider = future.get()
                bindCamera()
            } catch (t: Throwable) {
                listener?.onError(t)
            }
        }, { mainHandler.post(it) })
    }

    /** Unbind the camera and stop analysis. */
    fun stop() {
        cancelCountdown(notify = false)
        cameraProvider?.unbindAll()
        cameraProvider = null
        boundOwner = null
        imageCapture = null
        workExecutor?.shutdown()
        workExecutor = null
        setHint(Hint.SEARCHING)
    }

    /** Manual capture fallback — snaps immediately, ignoring stability. */
    fun capture() {
        val ic = imageCapture ?: run {
            listener?.onError(IllegalStateException("capture() before start()"))
            return
        }
        if (capturing) return
        capturing = true
        cancelCountdown(notify = false)
        val exec = workExecutor ?: Executors.newSingleThreadExecutor().also { workExecutor = it }
        ic.takePicture(
            exec,
            object : ImageCapture.OnImageCapturedCallback() {
                override fun onCaptureSuccess(image: ImageProxy) {
                    try {
                        val rotation = image.imageInfo.rotationDegrees
                        val buffer = image.planes[0].buffer
                        val bytes = ByteArray(buffer.remaining()).also { buffer.get(it) }
                        image.close()
                        val jpeg = downscaleJpeg(bytes, rotation)
                        mainHandler.post {
                            captured = true
                            capturing = false
                            listener?.onCaptured(jpeg)
                        }
                    } catch (t: Throwable) {
                        image.close()
                        mainHandler.post {
                            capturing = false
                            listener?.onError(t)
                        }
                    }
                }

                override fun onError(exception: ImageCaptureException) {
                    mainHandler.post {
                        capturing = false
                        listener?.onError(exception)
                    }
                }
            },
        )
    }

    /** Re-arm auto-capture after a capture (e.g. on "retake") with a fresh nonce. */
    fun rearm() {
        captureNonce = newNonce()
        captured = false
        capturing = false
        stableSince = 0L
        cancelCountdown(notify = false)
    }

    // ---------- Camera binding ----------

    private fun bindCamera() {
        val provider = cameraProvider ?: return
        val owner = boundOwner ?: return
        val exec = workExecutor ?: return
        try {
            provider.unbindAll()
            val preview = Preview.Builder().build().also {
                it.setSurfaceProvider(previewView.surfaceProvider)
            }
            val analysis = ImageAnalysis.Builder()
                .setBackpressureStrategy(ImageAnalysis.STRATEGY_KEEP_ONLY_LATEST)
                .build()
                .also { it.setAnalyzer(exec, LumaAnalyzer()) }
            val capture = ImageCapture.Builder()
                .setCaptureMode(ImageCapture.CAPTURE_MODE_MINIMIZE_LATENCY)
                .build()
            imageCapture = capture
            val selector = if (mode == Mode.SELFIE) {
                CameraSelector.DEFAULT_FRONT_CAMERA
            } else {
                CameraSelector.DEFAULT_BACK_CAMERA
            }
            provider.bindToLifecycle(owner, selector, preview, analysis, capture)
        } catch (t: Throwable) {
            listener?.onError(t)
        }
    }

    // ---------- Luma-based brightness + frame-diff stability ----------

    private inner class LumaAnalyzer : ImageAnalysis.Analyzer {
        private var prevCells: FloatArray? = null

        override fun analyze(image: ImageProxy) {
            try {
                val plane = image.planes[0] // Y plane of YUV_420_888
                val buf = plane.buffer
                val rowStride = plane.rowStride
                val pixStride = plane.pixelStride
                val w = image.width
                val h = image.height
                val cells = FloatArray(GRID * GRID)
                var total = 0f
                for (gy in 0 until GRID) {
                    val py = (gy * h) / GRID + h / (GRID * 2)
                    for (gx in 0 until GRID) {
                        val px = (gx * w) / GRID + w / (GRID * 2)
                        val v = (buf.get(py * rowStride + px * pixStride).toInt() and 0xFF).toFloat()
                        cells[gy * GRID + gx] = v
                        total += v
                    }
                }
                val meanLuma = total / (GRID * GRID)
                val prev = prevCells
                val motion = if (prev == null) {
                    Float.MAX_VALUE // first frame: unknown, treat as moving
                } else {
                    var d = 0f
                    for (i in cells.indices) d += abs(cells[i] - prev[i])
                    d / cells.size
                }
                prevCells = cells
                mainHandler.post { evaluate(meanLuma, motion) }
            } catch (t: Throwable) {
                mainHandler.post { listener?.onError(t) }
            } finally {
                image.close()
            }
        }
    }

    /** Main-thread state machine: hints, stability window, countdown. */
    private fun evaluate(meanLuma: Float, motion: Float) {
        if (captured || capturing) return
        val hint = when {
            meanLuma < minLuma -> Hint.TOO_DARK
            meanLuma > maxLuma -> Hint.TOO_BRIGHT
            motion > motionThreshold -> Hint.HOLD_STILL
            else -> Hint.STABLE
        }
        setHint(hint)
        if (!autoCapture) return
        val now = SystemClock.elapsedRealtime()
        if (hint == Hint.STABLE) {
            if (stableSince == 0L) stableSince = now
            if (now - stableSince >= stableMillis && countdownLeft < 0) startCountdown()
        } else {
            stableSince = 0L
            if (countdownLeft >= 0) cancelCountdown(notify = true)
        }
    }

    private fun setHint(hint: Hint) {
        if (hint == currentHint) return
        currentHint = hint
        overlay.invalidate()
        listener?.onHint(hint)
    }

    private val countdownTick = object : Runnable {
        override fun run() {
            if (countdownLeft < 0) return
            if (countdownLeft == 0) {
                countdownLeft = -1
                overlay.invalidate()
                capture()
                return
            }
            listener?.onCountdownTick(countdownLeft)
            overlay.invalidate()
            countdownLeft -= 1
            mainHandler.postDelayed(this, 1_000L)
        }
    }

    private fun startCountdown() {
        countdownLeft = countdownSeconds
        if (countdownLeft <= 0) {
            countdownLeft = -1
            capture()
        } else {
            countdownTick.run()
        }
    }

    private fun cancelCountdown(notify: Boolean) {
        mainHandler.removeCallbacks(countdownTick)
        val wasCounting = countdownLeft >= 0
        countdownLeft = -1
        overlay.invalidate()
        if (notify && wasCounting) listener?.onCountdownCancelled()
    }

    // ---------- JPEG output: rotate + downscale to maxDimension, q jpegQuality ----------

    private fun downscaleJpeg(bytes: ByteArray, rotationDegrees: Int): ByteArray {
        val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
        BitmapFactory.decodeByteArray(bytes, 0, bytes.size, bounds)
        var sample = 1
        while (max(bounds.outWidth, bounds.outHeight) / (sample * 2) >= maxDimension) sample *= 2
        val opts = BitmapFactory.Options().apply { inSampleSize = sample }
        var bmp = BitmapFactory.decodeByteArray(bytes, 0, bytes.size, opts)
            ?: throw IllegalStateException("could not decode captured JPEG")
        if (rotationDegrees != 0) {
            val m = Matrix().apply { postRotate(rotationDegrees.toFloat()) }
            val rotated = Bitmap.createBitmap(bmp, 0, 0, bmp.width, bmp.height, m, true)
            if (rotated != bmp) bmp.recycle()
            bmp = rotated
        }
        val maxSide = max(bmp.width, bmp.height)
        if (maxSide > maxDimension) {
            val scale = maxDimension.toFloat() / maxSide
            val scaled = Bitmap.createScaledBitmap(
                bmp,
                max(1, (bmp.width * scale).toInt()),
                max(1, (bmp.height * scale).toInt()),
                true,
            )
            if (scaled != bmp) bmp.recycle()
            bmp = scaled
        }
        val out = ByteArrayOutputStream()
        bmp.compress(Bitmap.CompressFormat.JPEG, jpegQuality, out)
        bmp.recycle()
        return out.toByteArray()
    }

    // ---------- Overlay: dim scrim with an oval/card punch-through + countdown ----------

    private inner class OverlayView(context: Context) : View(context) {
        private val density = resources.displayMetrics.density
        private val guidePath = Path()
        private val scrimColor = 0x99000000.toInt()
        private val clearPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            xfermode = PorterDuffXfermode(PorterDuff.Mode.CLEAR)
        }
        private val strokePaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            style = Paint.Style.STROKE
            strokeWidth = 3f * density
        }
        private val countdownPaint = Paint(Paint.ANTI_ALIAS_FLAG).apply {
            color = 0xFFFFFFFF.toInt()
            textAlign = Paint.Align.CENTER
            textSize = 72f * density
            isFakeBoldText = true
        }

        override fun onDraw(canvas: Canvas) {
            val w = width.toFloat()
            val h = height.toFloat()
            if (w <= 0f || h <= 0f) return

            guidePath.reset()
            if (mode == Mode.SELFIE) {
                val cx = w / 2f
                val cy = h * 0.44f
                val rw = min(w * 0.36f, h * 0.28f)
                val rh = rw * 1.35f
                guidePath.addOval(RectF(cx - rw, cy - rh, cx + rw, cy + rh), Path.Direction.CW)
            } else {
                // ID-1 card aspect (85.6 x 54 mm ~= 1.586)
                val cx = w / 2f
                val cy = h * 0.45f
                val rw = min(w * 0.44f, h * 0.35f * 1.586f)
                val rh = rw / 1.586f
                val r = 16f * density
                guidePath.addRoundRect(RectF(cx - rw, cy - rh, cx + rw, cy + rh), r, r, Path.Direction.CW)
            }

            val layer = canvas.saveLayer(0f, 0f, w, h, null)
            canvas.drawColor(scrimColor)
            canvas.drawPath(guidePath, clearPaint)
            canvas.restoreToCount(layer)

            strokePaint.color = when (currentHint) {
                Hint.STABLE -> 0xFF34D399.toInt() // green
                Hint.SEARCHING -> 0xFFFFFFFF.toInt() // white
                else -> 0xFFF59E0B.toInt() // amber
            }
            canvas.drawPath(guidePath, strokePaint)

            if (countdownLeft > 0) {
                val ty = h / 2f - (countdownPaint.ascent() + countdownPaint.descent()) / 2f
                canvas.drawText(countdownLeft.toString(), w / 2f, ty, countdownPaint)
            }
        }
    }

    override fun onDetachedFromWindow() {
        stop()
        super.onDetachedFromWindow()
    }

    private companion object {
        const val GRID = 16

        val rng = SecureRandom()
        fun newNonce(): String {
            val b = ByteArray(16)
            rng.nextBytes(b)
            return b.joinToString("") { "%02x".format(it) }
        }
    }
}
